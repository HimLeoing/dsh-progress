import assert from 'node:assert/strict'
import {createLocalEvidence,recordLocalOperation,estimateLocalScope} from '../lib/local-estimator.js'
import {localWorkFacts,localVerificationGrade} from '../lib/local-work-evidence.js'
const complete=(e,name,args,phase='implement',output='')=>{const facts=localWorkFacts(name,args);recordLocalOperation(e,{...facts,name,phase,status:'completed',verification:localVerificationGrade(facts,output)})}
const evidence=createLocalEvidence('Implement a complete web application')
recordLocalOperation(evidence,{name:'present',phase:'deliver',status:'completed',label:'Preview one draft'})
assert.ok(estimateLocalScope(evidence.root)<.8,'presenting a draft without implemented/verified work must not imply98.5% completion')
const tiny=localWorkFacts('write',{path:'app.js',content:'x'}),large=localWorkFacts('write',{path:'app.js',content:'const privateBody = 1;\n'.repeat(400)})
assert.ok(large.credit>tiny.credit&&large.credit<=3.5,'substantive output receives bounded size-aware evidence')
assert.doesNotMatch(JSON.stringify(large),/privateBody|app\.js/,'work facts do not retain file bodies or paths')
const writes=createLocalEvidence('Implement a web application')
for(let i=0;i<100;i++)complete(writes,'write',{path:'app.js',content:'unchanged'})
assert.equal(writes.root.successes,1,'identical material cannot repeatedly advance progress')
const before=estimateLocalScope(writes.root);complete(writes,'write',{path:'app.js',content:'changed'});assert.ok(estimateLocalScope(writes.root)>before)
complete(writes,'bash',{command:'npm test'},'verify','# pass 24')
const material=writes.root.material;complete(writes,'write',{path:'app.js',content:'unchanged'})
assert.ok(writes.root.material>material,'returning to an older body is real changed material, not an all-history duplicate')
assert.equal(writes.root.verified,-1,'a rollback invalidates checks of the replaced body')
complete(writes,'edit',{path:'app.js',old_string:'a',new_string:'b'});complete(writes,'edit',{path:'app.js',old_string:'a',new_string:'b'})
assert.equal(writes.root.successes,6,'identical edits can replace different occurrences and cannot be proven duplicates')
const reads=createLocalEvidence('Research examples')
complete(reads,'web_search',{query:'first'},'discover');complete(reads,'web_search',{query:'second'},'discover');assert.equal(reads.root.units[0],2,'different searches retain independent evidence')
const unverified=createLocalEvidence('Build a complete production app')
for(let i=0;i<12;i++)complete(unverified,'write',{path:`file-${i}.js`,content:'const x = 1;\n'.repeat(40)})
const initial=estimateLocalScope(unverified.root)
complete(unverified,'bash',{command:'node --check file-0.js',description:'Final acceptance all tests passed'},'verify')
assert.notEqual(unverified.root.verified,unverified.root.material,'a grandiose label cannot promote a syntax check')
const syntax=estimateLocalScope(unverified.root)
complete(unverified,'bash',{command:'npm test'},'verify','# pass 24\n# fail 0')
assert.equal(unverified.root.verificationGrade,3);assert.equal(unverified.root.verified,unverified.root.material)
assert.ok(estimateLocalScope(unverified.root)>syntax&&syntax>=initial)
const verified=estimateLocalScope(unverified.root)
complete(unverified,'write',{path:'fix.js',content:'const fixed=true;'})
assert.ok(estimateLocalScope(unverified.root)<verified,'new material invalidates prior checks instead of retaining their bonus')
recordLocalOperation(unverified,{name:'bash',phase:'verify',status:'failed'});assert.equal(unverified.root.debt,1)
complete(unverified,'bash',{command:'npm test'},'verify','# pass 24')
assert.equal(unverified.root.debt,0,'successful substantive recheck clears outstanding rework debt')
assert.equal(unverified.root.failures,1,'historical failure diagnostics remain intact')
const small=createLocalEvidence('Implement a tiny single function'),broad=createLocalEvidence('Implement a complete production application')
assert.ok(small.root.prior[1]<broad.root.prior[1],'cold priors distinguish narrow work from broad projects without history')
for(const e of [small,broad])complete(e,'write',{path:'one.js',content:'const x=1;'})
complete(broad,'bash',{command:'npm test'},'verify','# pass 24')
assert.ok(estimateLocalScope(broad.root)<.8,'a small tested fragment cannot establish nearly complete project coverage')
const unknown=createLocalEvidence('Build app')
for(let i=0;i<6;i++)complete(unknown,'write',{path:'same.js'})
assert.equal(unknown.root.units[1],6,'missing material is not proof of identical writes')
console.log('Local quality rc1 passed: draft vs delivery, work size, privacy, semantic duplicates, distinct reads, graded checks, rework debt, cold scope and sparse events')
